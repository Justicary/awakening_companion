--- Determina el bracket BiS por defecto según el nivel del jugador
function ns.GetDefaultBiSBracket(level)
    local lvl = level or (UnitLevel and UnitLevel("player")) or 60
    if lvl <= 25 then return "15-25"
    elseif lvl <= 40 then return "26-40"
    elseif lvl <= 52 then return "41-52"
    elseif lvl < 60 then return "pre-raid"
    else return "raid-p1" end
end

--- Verifica si el jugador tiene el objeto equipado o en sus bolsas
function ns.GetPlayerItemStatus(itemID)
    if not itemID or itemID == 0 then return false, false end

    -- 1. Escaneo seguro de ranuras equipadas (1 a 19)
    if GetInventoryItemID then
        for slot = 1, 19 do
            local ok, invID = pcall(GetInventoryItemID, "player", slot)
            if ok and invID == itemID then
                return true, false
            end
        end
    end

    -- 2. Escaneo seguro de bolsas del jugador (0 a NUM_BAG_SLOTS)
    local numBags = NUM_BAG_SLOTS or 4
    for bag = 0, numBags do
        local numSlots = 0
        if C_Container and C_Container.GetContainerNumSlots then
            numSlots = C_Container.GetContainerNumSlots(bag) or 0
        elseif GetContainerNumSlots then
            numSlots = GetContainerNumSlots(bag) or 0
        end

        for slot = 1, numSlots do
            local id
            if C_Container and C_Container.GetContainerItemID then
                id = C_Container.GetContainerItemID(bag, slot)
            elseif GetContainerItemID then
                id = GetContainerItemID(bag, slot)
            end

            if id == itemID then
                return false, true
            end
        end
    end

    return false, false
end

--- Obtiene los metadatos de obtención del objeto (Jefe, Zona, Drop, etc.)
function ns.GetBiSItemMetadata(itemID)
    if not itemID or itemID == 0 then return nil end
    local pre = ns.Data.BiSItems and ns.Data.BiSItems[itemID]
    if pre then return pre end

    local itemName
    if C_Item and C_Item.GetItemInfo then
        local ok, n = pcall(C_Item.GetItemInfo, itemID)
        if ok and n then itemName = n end
    end
    if not itemName and _G.GetItemInfo then
        local ok, n = pcall(_G.GetItemInfo, itemID)
        if ok and n then itemName = n end
    end

    return {
        name = itemName or ("Objeto #" .. itemID),
        source = "Mundo Clásico",
        type = "Kill",
        zone = "Azeroth",
        drop = "Variable"
    }
end

--- Obtiene estadísticas de avance BiS (obtenidos / total)
function ns.GetBiSProgress(classKey, bracketKey, specKey)
    classKey = classKey or (UnitClass and select(2, UnitClass("player"))) or "WARRIOR"
    local classData = ns.Data.BiS and (ns.Data.BiS[classKey] or ns.Data.BiS[classKey:upper()] or ns.Data.BiS["WARRIOR"])
    if not classData or not classData.sets then return 0, 0, 0 end

    bracketKey = bracketKey or ns.GetDefaultBiSBracket()
    local bracketSets = classData.sets[bracketKey] or classData.sets["raid-p1"] or classData.sets["pre-raid"]
    if not bracketSets then return 0, 0, 0 end

    local spec = specKey or (classData.specs and classData.specs[1] and classData.specs[1].key)
    local set = bracketSets[spec] or (classData.specs and classData.specs[1] and bracketSets[classData.specs[1].key])
    if not set then return 0, 0, 0 end

    local total = 0
    local acquired = 0
    for _, slotInfo in ipairs(ns.Data.BiSSlotsOrder or {}) do
        local iid = set[slotInfo.key]
        if iid and iid > 0 then
            total = total + 1
            local eq, inB = ns.GetPlayerItemStatus(iid)
            if eq or inB then
                acquired = acquired + 1
            end
        end
    end
    local pct = total > 0 and math.floor((acquired / total) * 100) or 0
    return acquired, total, pct
end
